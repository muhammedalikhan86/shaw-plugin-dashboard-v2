# Regenerates uat-data.js for index.html (the test site page) from the main checkout's deploy tags
# (deploy/uat/<part>-<yyyyMMdd-HHmmss>, made by deploy.ps1), the hand-kept uat-notes.json, and
# uat-status.json (the last service check, written by update-uat-status.ps1).
# It also reads the live site's deploy tags (deploy/prod/<part>-<yyyyMMdd-HHmmss>) into prod.deploys
# (part, at, version: the tag's stamp), for the Prod tabs. Read only: git for-each-ref, nothing else.
# uat-notes.json may carry prodReleases (same shape as releases) for the Prod log.
# The hub runs it after each test-site deploy, then commits and pushes this repo.
# This repo is public: only part names, commits, commit subjects and times go out. Never a server
# name, share path, address or person's email.
param(
    [string]$Source = (Join-Path (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)) 'shaw-plugin-dashboard')
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$lines = @(git -C $Source for-each-ref 'refs/tags/deploy/uat' --format='%(refname:short)|%(objectname:short=8)|%(contents:subject)')
if ($LASTEXITCODE -ne 0) { throw "git for-each-ref failed in $Source" }

$deploys = foreach ($line in $lines) {
    $name, $sha, $subject = $line -split '\|', 3
    if ($name -notmatch '^deploy/uat/(?<part>.+)-(?<d>\d{8})-(?<t>\d{6})$') { continue }
    $when = [datetime]::ParseExact($Matches.d + $Matches.t, 'yyyyMMddHHmmss', $null)
    [ordered]@{
        part    = $Matches.part
        at      = $when.ToString('yyyy-MM-ddTHH:mm:ss')
        commit  = $sha
        subject = $subject
    }
}
$deploys = @($deploys | Sort-Object { $_.at } -Descending)

$prodLines = @(git -C $Source for-each-ref 'refs/tags/deploy/prod' --format='%(refname:short)')
if ($LASTEXITCODE -ne 0) { throw "git for-each-ref failed in $Source" }

$prodDeploys = foreach ($line in $prodLines) {
    if ($line -notmatch '^deploy/prod/(?<part>.+)-(?<d>\d{8})-(?<t>\d{6})$') { continue }
    $when = [datetime]::ParseExact($Matches.d + $Matches.t, 'yyyyMMddHHmmss', $null)
    [ordered]@{
        part    = $Matches.part
        at      = $when.ToString('yyyy-MM-ddTHH:mm:ss')
        version = "$($Matches.d)-$($Matches.t)"
    }
}
$prodDeploys = @($prodDeploys | Sort-Object { $_.at } -Descending)

$notesPath = Join-Path $here 'uat-notes.json'
$notes = if (Test-Path $notesPath) { Get-Content $notesPath -Raw -Encoding UTF8 | ConvertFrom-Json } else { $null }

$statusPath = Join-Path $here 'uat-status.json'
$status = if (Test-Path $statusPath) { Get-Content $statusPath -Raw -Encoding UTF8 | ConvertFrom-Json } else { $null }

$data = [ordered]@{
    generated = (Get-Date).ToString('yyyy-MM-ddTHH:mm:ss')
    deploys   = $deploys
    notes     = $notes
    status    = $status
    prod      = [ordered]@{ deploys = $prodDeploys }
}
$json = ConvertTo-Json -InputObject $data -Depth 6 -Compress
$js = "// Generated by update-uat-data.ps1 from the deploy tags, uat-notes.json and uat-status.json. Do not edit by hand.`nwindow.UAT_DATA = $json;`n"
[System.IO.File]::WriteAllText((Join-Path $here 'uat-data.js'), $js, (New-Object System.Text.UTF8Encoding $false))
Write-Output "uat-data.js written ($($deploys.Count) deploys, $($prodDeploys.Count) live deploys)"
